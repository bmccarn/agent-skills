#!/bin/bash
# Make a vault shareable with someone who doesn't have these skills:
# copy the vault skills and the Stop hook into <vault>/skills/ and write the
# install steps. Generated from the installed copies; rerun to refresh, never edit
# the copies in the vault. Leaves the result uncommitted for review.
#
#   make-kit.sh <vault-dir>
set -u
HERE="$(cd "$(dirname "$0")/.." && pwd -P)"
SKILLS="$(cd "$HERE/.." && pwd -P)"
V="${1:?usage: make-kit.sh <vault-dir>}"
[ -f "$V/AGENTS.md" ] && [ -f "$V/HOME.md" ] && [ -d "$V/bases" ] || { echo "STOP: $V is not a vault" >&2; exit 1; }
if [ -d "$V/skills" ] && [ ! -f "$V/skills/.generated" ]; then
  echo "STOP: $V/skills exists and was not made by make-kit.sh; leaving it alone" >&2; exit 1
fi
rm -rf "$V/skills"; mkdir -p "$V/skills"
for s in project-vault vault-sweep; do cp -R "$SKILLS/$s" "$V/skills/$s"; done
find "$V/skills" -name .DS_Store -delete
rev=$(git -C "$SKILLS" rev-parse --short HEAD 2>/dev/null || echo unknown)
echo "generated by vault-workspace-setup/scripts/make-kit.sh from skills revision $rev; rerun it to refresh" > "$V/skills/.generated"
cat > "$V/skills/README.md" <<'EOF'
# Installing this vault's agent skills

Copies of the skills that read and write this vault, for anyone without them. Install once per machine, from the workspace folder that holds this vault (the folder you start your agent in):

```bash
mkdir -p .claude/skills .agents/skills
for s in project-vault vault-sweep; do
  ln -sfn "../../<vault-folder>/skills/$s" ".claude/skills/$s"    # Claude Code
  ln -sfn "../../<vault-folder>/skills/$s" ".agents/skills/$s"    # Codex and others
done
```

Link the skill folder, not the SKILL.md inside it: Claude Code finds a linked folder but ignores a linked SKILL.md.

Claude Code's session-end reminder: add to `.claude/settings.local.json` in the same folder:

```json
{"hooks": {"Stop": [{"hooks": [{"type": "command", "timeout": 15,
  "command": "bash \"$CLAUDE_PROJECT_DIR/<vault-folder>/skills/project-vault/hooks/vault-review-stop.sh\""}]}]}}
```

Arm the commit guard in your clone: `git -C <vault-folder> config core.hooksPath .githooks`.

Check it: start your agent in the workspace folder and ask whether skills named project-vault and vault-sweep are available.
EOF
echo "kit written to $V/skills (skills revision $rev). Review, then commit it in the vault."
